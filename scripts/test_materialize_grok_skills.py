#!/usr/bin/env python3
"""Selftests for materialize-grok-skills.py against a real temp tree.

UNIT_TEST_JUSTIFIED: this is a pure text/filesystem transform with zero
network I/O — the live grok inspect check runs separately after install.
"""
from __future__ import annotations

import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
SCRIPT = HERE / "materialize-grok-skills.py"

# Import the transform so we assert the same functions the CLI runs.
sys.path.insert(0, str(HERE))
import importlib.util

spec = importlib.util.spec_from_file_location("materialize_grok_skills", SCRIPT)
mod = importlib.util.module_from_spec(spec)
assert spec.loader is not None
spec.loader.exec_module(mod)


def fail(msg: str) -> None:
    raise AssertionError(msg)


def test_rewrite_name_and_slash() -> None:
    src = """---
name: rosetta-research
description: "Trigger: /rosetta-research {tech}"
---

# Rosetta Research

Use /rosetta-research then /rosetta-bootstrap.
Path stays skills/rosetta-research/SKILL.md
"""
    out = mod.rewrite_skill_text(src)
    if "name: research" not in out:
        fail(f"frontmatter name not shortened:\n{out}")
    if "name: rosetta-research" in out:
        fail("long frontmatter name survived")
    if "/rosetta:research" not in out or "/rosetta:bootstrap" not in out:
        fail(f"slash commands not rewritten:\n{out}")
    if re.search(r"(?<![A-Za-z0-9._-])/rosetta-research\b", out):
        fail(f"long slash survived:\n{out}")
    if "skills/rosetta-research/SKILL.md" not in out:
        fail("path reference was rewritten; it must stay a filesystem path")
    if "skills/rosetta:research" in out:
        fail("path was turned into a slash name")


def test_materialize_temp_tree() -> None:
    with tempfile.TemporaryDirectory(prefix="grok-skills-src-") as tmp:
        root = Path(tmp)
        src = root / "skills" / "rosetta-research"
        src.mkdir(parents=True)
        (src / "SKILL.md").write_text(
            "---\nname: rosetta-research\ndescription: x\n---\n\n# R\n/rosetta-research\n"
        )
        assets = src / "assets"
        assets.mkdir()
        (assets / "rosetta_config.py").write_text("print('ok')\n")
        # the other six must exist
        for long, _short in mod.SKILL_MAP:
            d = root / "skills" / long
            d.mkdir(parents=True, exist_ok=True)
            if not (d / "SKILL.md").exists():
                (d / "SKILL.md").write_text(
                    f"---\nname: {long}\ndescription: d\n---\n\n# {long}\n/{long}\n"
                )
        dest = root / "grok-skills"
        written = mod.materialize_into(root, dest)
        if len(written) != len(mod.SKILL_MAP):
            fail(f"expected {len(mod.SKILL_MAP)} skills, got {len(written)}")
        research = dest / "research" / "SKILL.md"
        body = research.read_text()
        if "name: research" not in body:
            fail(body)
        if "/rosetta:research" not in body:
            fail(body)
        if BANNER_MISSING(body):
            fail("generated banner missing")
        copied = dest / "research" / "assets" / "rosetta_config.py"
        if not copied.is_file() or copied.read_text() != "print('ok')\n":
            fail("assets/ not copied")
        agents = dest / "AGENTS.md"
        if not agents.is_file() or "Do not edit these files" not in agents.read_text():
            fail("generated AGENTS.md missing or missing do-not-edit rule")
        # --check on this tree
        import contextlib, io
        quiet = io.StringIO()
        with contextlib.redirect_stdout(quiet), contextlib.redirect_stderr(quiet):
            rc = mod.check(root)
        if rc != 0:
            fail("fresh generate failed --check")
        (dest / "research" / "SKILL.md").write_text("tampered\n")
        with contextlib.redirect_stdout(quiet), contextlib.redirect_stderr(quiet):
            rc_tamper = mod.check(root)
        if rc_tamper == 0:
            fail("--check passed after tamper")


def BANNER_MISSING(body: str) -> bool:
    return "Generated by scripts/materialize-grok-skills.py" not in body


def test_repo_pack_is_current() -> None:
    """The committed grok-skills/ tree must match a fresh generate."""
    rc = subprocess.run(
        [sys.executable, str(SCRIPT), "--check", "--root", str(ROOT)],
        capture_output=True, text=True,
    )
    if rc.returncode != 0:
        fail(f"committed grok-skills drifted:\n{rc.stdout}{rc.stderr}")


def test_plugin_json_points_at_grok_skills() -> None:
    plugin = json.loads((ROOT / ".grok-plugin" / "plugin.json").read_text())
    if plugin.get("name") != "rosetta":
        fail(f"plugin name should be rosetta, got {plugin.get('name')}")
    if plugin.get("skills") != "./grok-skills":
        fail(f"plugin.json skills path should be ./grok-skills, got {plugin.get('skills')}")
    expected = {short for _long, short in mod.SKILL_MAP}
    found = {
        p.parent.name
        for p in (ROOT / "grok-skills").glob("*/SKILL.md")
    }
    if found != expected:
        fail(f"grok-skills names {found} != {expected}")


def main() -> int:
    tests = [
        test_rewrite_name_and_slash,
        test_materialize_temp_tree,
        test_plugin_json_points_at_grok_skills,
        test_repo_pack_is_current,
    ]
    failures: list[str] = []
    for fn in tests:
        try:
            fn()
            print(f"  ok  {fn.__name__}")
        except Exception as exc:
            print(f"  FAIL {fn.__name__}: {exc}", file=sys.stderr)
            failures.append(fn.__name__)
    if failures:
        print(f"FAIL: {len(failures)} test(s)", file=sys.stderr)
        return 1
    print("ok — materialize-grok-skills rewrite + pack + plugin.json")
    return 0


if __name__ == "__main__":
    sys.exit(main())
