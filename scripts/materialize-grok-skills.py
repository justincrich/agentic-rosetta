#!/usr/bin/env python3
"""Generate Grok plugin skills with short names.

Canonical skills stay at skills/rosetta-* so Claude / Codex / OpenCode /
skillshare keep /rosetta-research. Grok namespaces by plugin.json name, so
the same frontmatter would become /rosetta:rosetta-research. This writer
emits grok-skills/{short}/SKILL.md with name: {short} so the slash is
/rosetta:research. .grok-plugin/plugin.json points skills at ./grok-skills.

The generated tree is committed so `grok plugin install` from a clone works
without a generate step. --check fails if grok-skills/ drifted from source.
"""
from __future__ import annotations

import argparse
import filecmp
import re
import shutil
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
DEFAULT_ROOT = HERE.parent

# Longer keys first so replace() cannot nibble a prefix of another id.
SKILL_MAP: tuple[tuple[str, str], ...] = (
    ("rosetta-stress-test", "stress-test"),
    ("rosetta-ab-test", "ab-test"),
    ("rosetta-bootstrap", "bootstrap"),
    ("rosetta-research", "research"),
    ("rosetta-validate", "validate"),
    ("rosetta-upgrade", "upgrade"),
    ("rosetta-sync", "sync"),
)

BANNER = (
    "<!-- Generated by scripts/materialize-grok-skills.py. "
    "Edit skills/rosetta-*/SKILL.md — do not edit this file. -->"
)

README = """# grok-skills/

Generated Grok plugin skill tree. Short directory + frontmatter names so
Grok advertises `/rosetta:research`, `/rosetta:bootstrap`, … instead of
`/rosetta:rosetta-research`.

Do not edit these files. Change `skills/rosetta-*/SKILL.md` and run:

```
python3 scripts/materialize-grok-skills.py
```

`--check` (wired into `scripts/assert-no-drift.sh`) fails if this tree
drifts from the canonical skills.
"""

AGENTS = """# grok-skills/ — directory system prompt

You are in the **generated Grok pack**. Do not edit these files.

Canonical skill bodies live in [`../skills/`](../skills/). After changing
those, regenerate:

```
python3 scripts/materialize-grok-skills.py
```

`--check` (wired into `scripts/assert-no-drift.sh`) fails if this tree
drifts from `skills/rosetta-*`.

Why a second tree exists: Grok namespaces by `.grok-plugin/plugin.json`
`name` (`rosetta`). Shipping `name: rosetta-research` would advertise
`/rosetta:rosetta-research`. Short ids (`research`, `bootstrap`, …) make
the slash `/rosetta:research`.

More: [`README.md`](README.md). Root contract: [`../AGENTS.md`](../AGENTS.md).
"""


def rewrite_skill_text(text: str) -> str:
    """Rewrite frontmatter name and /rosetta-* slash triggers for Grok."""
    def repl_name(match: re.Match[str]) -> str:
        long = match.group(1)
        mapping = dict(SKILL_MAP)
        return f"name: {mapping.get(long, long)}"

    out = re.sub(
        r"(?m)^name:\s+(rosetta-[a-z0-9-]+)\s*$",
        repl_name,
        text,
        count=1,
    )
    # Slash commands only. Do not rewrite filesystem paths
    # (skills/rosetta-research/SKILL.md must stay a path).
    for long, short in SKILL_MAP:
        out = re.sub(
            rf"(?<![A-Za-z0-9._-])/{re.escape(long)}\b",
            f"/rosetta:{short}",
            out,
        )
    return out


def insert_banner(text: str) -> str:
    if not text.startswith("---"):
        raise ValueError("SKILL.md is missing YAML frontmatter")
    close = text.find("\n---", 3)
    if close < 0:
        raise ValueError("SKILL.md frontmatter is unclosed")
    end = close + len("\n---")
    rest = text[end:]
    if rest.startswith("\n"):
        rest = rest[1:]
    return text[:end] + "\n\n" + BANNER + "\n" + rest


def render_skill(src_text: str) -> str:
    return insert_banner(rewrite_skill_text(src_text))


def materialize_into(root: Path, dest: Path) -> list[Path]:
    """Write the short-name tree under dest. Returns written SKILL.md paths."""
    if dest.exists():
        shutil.rmtree(dest)
    dest.mkdir(parents=True)
    (dest / "README.md").write_text(README)
    (dest / "AGENTS.md").write_text(AGENTS)
    written: list[Path] = []
    for long, short in SKILL_MAP:
        src_dir = root / "skills" / long
        src_md = src_dir / "SKILL.md"
        if not src_md.is_file():
            raise FileNotFoundError(f"missing canonical skill {src_md}")
        out_dir = dest / short
        out_dir.mkdir()
        out_md = out_dir / "SKILL.md"
        out_md.write_text(render_skill(src_md.read_text()))
        written.append(out_md)
        src_assets = src_dir / "assets"
        if src_assets.is_dir():
            shutil.copytree(src_assets, out_dir / "assets")
    return written


def trees_match(expected: Path, actual: Path) -> list[str]:
    """Return human-readable drift lines (empty = identical)."""
    drift: list[str] = []
    if not actual.is_dir():
        return [f"missing {actual}"]
    exp_files = {p.relative_to(expected) for p in expected.rglob("*") if p.is_file()}
    act_files = {p.relative_to(actual) for p in actual.rglob("*") if p.is_file()}
    for rel in sorted(exp_files - act_files):
        drift.append(f"missing {rel}")
    for rel in sorted(act_files - exp_files):
        drift.append(f"extra {rel}")
    for rel in sorted(exp_files & act_files):
        a = expected / rel
        b = actual / rel
        if not filecmp.cmp(a, b, shallow=False):
            drift.append(f"differs {rel}")
    return drift


def check(root: Path) -> int:
    dest = root / "grok-skills"
    with tempfile.TemporaryDirectory(prefix="grok-skills-check-") as tmp:
        expected = Path(tmp) / "grok-skills"
        materialize_into(root, expected)
        drift = trees_match(expected, dest)
    if drift:
        print("FAIL: grok-skills/ drifted from skills/rosetta-*", file=sys.stderr)
        for line in drift:
            print(f"  {line}", file=sys.stderr)
        print("Run: python3 scripts/materialize-grok-skills.py", file=sys.stderr)
        return 1
    print(f"ok — grok-skills/ matches {len(SKILL_MAP)} canonical skills")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--root",
        type=Path,
        default=DEFAULT_ROOT,
        help="plugin repo root (default: this checkout)",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify grok-skills/ matches a fresh generate; write nothing",
    )
    args = parser.parse_args(argv)
    root = args.root.resolve()
    if args.check:
        return check(root)
    written = materialize_into(root, root / "grok-skills")
    for path in written:
        rel = path.relative_to(root)
        name = path.parent.name
        print(f"  wrote {rel}  (/rosetta:{name})")
    print(f"ok — {len(written)} Grok skills under grok-skills/")
    return 0


if __name__ == "__main__":
    sys.exit(main())
